-- PostgreSQL. Los mínimos de las relaciones 1:1 y del catálogo se comprueban
-- al final de la transacción para permitir insertar primero la entidad y luego
-- su perfil, biblioteca o relaciones. Cargar el seed dentro de una transacción.
CREATE TABLE countries (
    country_code char(2) PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE subscriptions (
    subscription_id integer PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    monthly_price_mxn numeric(8,2) NOT NULL CHECK (monthly_price_mxn >= 0),
    has_ads boolean NOT NULL
);
CREATE TABLE subscribers (
    subscriber_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    registered_at date NOT NULL,
    subscription_id integer NOT NULL REFERENCES subscriptions(subscription_id)
);
CREATE TABLE profiles (
    subscriber_id integer PRIMARY KEY REFERENCES subscribers(subscriber_id),
    display_name varchar(100) NOT NULL,
    photo varchar(255),
    country_code char(2) NOT NULL REFERENCES countries(country_code)
);
CREATE TABLE libraries (
    subscriber_id integer PRIMARY KEY REFERENCES subscribers(subscriber_id)
);
CREATE TABLE artists (
    artist_id varchar(10) PRIMARY KEY,
    name varchar(150) NOT NULL,
    country_code char(2) NOT NULL REFERENCES countries(country_code)
);
CREATE TABLE genres (
    genre_id integer PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE songs (
    song_id integer PRIMARY KEY,
    title varchar(200) NOT NULL,
    duration_seconds integer NOT NULL CHECK (duration_seconds > 0),
    genre_id integer NOT NULL REFERENCES genres(genre_id)
);
CREATE TABLE albums (
    album_id integer PRIMARY KEY,
    title varchar(200) NOT NULL,
    release_year integer NOT NULL CHECK (release_year BETWEEN 1900 AND 2100),
    cover varchar(255) NOT NULL,
    artist_id varchar(10) REFERENCES artists(artist_id)
);
CREATE TABLE artist_song (
    artist_id varchar(10) NOT NULL REFERENCES artists(artist_id),
    song_id integer NOT NULL REFERENCES songs(song_id),
    role varchar(20) NOT NULL CHECK (role IN ('principal', 'feat.')),
    PRIMARY KEY (artist_id, song_id)
);
CREATE TABLE album_song (
    album_id integer NOT NULL REFERENCES albums(album_id),
    song_id integer NOT NULL REFERENCES songs(song_id),
    track_number integer NOT NULL CHECK (track_number > 0),
    PRIMARY KEY (album_id, song_id),
    UNIQUE (album_id, track_number)
);
CREATE TABLE playlists (
    playlist_id integer PRIMARY KEY,
    subscriber_id integer NOT NULL REFERENCES subscribers(subscriber_id),
    name varchar(200) NOT NULL,
    created_at date NOT NULL
);
CREATE TABLE playlist_song (
    playlist_id integer NOT NULL REFERENCES playlists(playlist_id),
    song_id integer NOT NULL REFERENCES songs(song_id),
    position integer NOT NULL CHECK (position > 0),
    added_at date NOT NULL,
    PRIMARY KEY (playlist_id, song_id),
    UNIQUE (playlist_id, position)
);
CREATE TABLE library_song (
    subscriber_id integer NOT NULL REFERENCES libraries(subscriber_id),
    song_id integer NOT NULL REFERENCES songs(song_id),
    PRIMARY KEY (subscriber_id, song_id)
);
CREATE TABLE library_album (
    subscriber_id integer NOT NULL REFERENCES libraries(subscriber_id),
    album_id integer NOT NULL REFERENCES albums(album_id),
    PRIMARY KEY (subscriber_id, album_id)
);

CREATE FUNCTION check_account_complete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM subscribers s
               LEFT JOIN profiles p USING (subscriber_id)
               LEFT JOIN libraries l USING (subscriber_id)
               WHERE p.subscriber_id IS NULL OR l.subscriber_id IS NULL) THEN
        RAISE EXCEPTION 'Cada suscriptor debe tener perfil y biblioteca' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER subscriber_complete AFTER INSERT OR UPDATE ON subscribers
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_account_complete();
CREATE CONSTRAINT TRIGGER profile_required AFTER DELETE OR UPDATE ON profiles
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_account_complete();
CREATE CONSTRAINT TRIGGER library_required AFTER DELETE OR UPDATE ON libraries
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_account_complete();

CREATE FUNCTION check_catalog_complete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM songs s WHERE NOT EXISTS
        (SELECT 1 FROM artist_song a WHERE a.song_id = s.song_id)) THEN
        RAISE EXCEPTION 'Cada canción debe acreditar al menos un artista' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM albums a WHERE NOT EXISTS
        (SELECT 1 FROM album_song x WHERE x.album_id = a.album_id)) THEN
        RAISE EXCEPTION 'Cada álbum debe contener al menos una canción' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER song_credit_required AFTER INSERT OR UPDATE ON songs
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_complete();
CREATE CONSTRAINT TRIGGER song_credit_preserved AFTER DELETE OR UPDATE ON artist_song
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_complete();
CREATE CONSTRAINT TRIGGER album_tracks_required AFTER INSERT OR UPDATE ON albums
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_complete();
CREATE CONSTRAINT TRIGGER album_tracks_preserved AFTER DELETE OR UPDATE ON album_song
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_complete();
